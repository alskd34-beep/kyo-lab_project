-- ─────────────────────────────────────────────────────────────────────────────
-- QC 작업 진행 단계 확장
--   기존: 진행중 / 검토중 / 완료 / 지연
--   변경: 진행중 → 검토전 → 검토중 → 승인전 → 승인완료   (+ 지연은 납기 표시로 유지)
--
-- '완료'는 최종 단계명이 '승인완료'로 바뀌었으므로 기존 행을 일괄 전환한다.
-- '검토중'에 머물러 있던 기존 행은 의미가 그대로라 손대지 않는다.
-- 단계 정의는 types/qc-status.ts 가 단일 기준이다.
-- ─────────────────────────────────────────────────────────────────────────────

-- 1) 작업 상태
update qc_jobs
   set status = '승인완료'
 where status = '완료';

-- 2) 오더 상태 (작업과 동기화되어 있음)
update pct_orders
   set status = '승인완료'
 where status = '완료';

-- 3) 컬럼 주석 갱신 (제약이 아니라 문서 역할)
comment on column qc_jobs.status is
  '진행중/검토전/검토중/승인전/승인완료/지연 — types/qc-status.ts 참조';
comment on column pct_orders.status is
  '대기/진행중/검토전/검토중/승인전/승인완료/지연/삭제 — types/qc-status.ts 참조';
